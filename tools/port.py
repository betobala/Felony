"""Turn a fresh copy of the O&C firmware (firmware/software/o_c_REV) into src/oc, ready to build in Rack.

Only the hardware drivers change: DAC, ADC, display, SPI, the frequency meter and the ARM DSP
intrinsics. Apps, menus, UI and storage stay as written. Run from the repository root:
    python tools/port.py
"""
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'firmware', 'software', 'o_c_REV')
DST = os.path.join(ROOT, 'src', 'oc')
DRV = os.path.join(ROOT, 'tools', 'drivers')


def path(*p):
    return os.path.join(DST, *p)


def read(p):
    with open(p, encoding='utf-8', errors='replace') as f:
        return f.read()


def write(p, s):
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)


def sub(p, old, new, count=1):
    s = read(path(p))
    if old not in s:
        raise SystemExit(f'{p}: pattern not found: {old[:60]!r}')
    write(path(p), s.replace(old, new, count))


shutil.rmtree(DST, ignore_errors=True)
shutil.copytree(SRC, DST, ignore=shutil.ignore_patterns('resources'))

# drivers replaced wholesale by tools/drivers/*
for rel in ['OC_ADC.cpp', 'src/drivers/SH1106_128x64_driver.cpp', 'util/util_SPIFIFO.h', 'extern/dspinst.h',
            'src/drivers/FreqMeasure/OC_FreqMeasure.h']:
    shutil.copy(os.path.join(DRV, rel.replace('/', '__')), path(*rel.split('/')))
for rel in ['src/drivers/FreqMeasure/OC_FreqMeasure.cpp', 'src/drivers/FreqMeasure/OC_FreqMeasureCapture.h']:
    os.remove(path(*rel.split('/')))
shutil.rmtree(path('src', 'drivers', 'ADC'))
os.makedirs(path('src', 'drivers', 'ADC'))
shutil.copy(os.path.join(DRV, 'OC_util_ADC.h'), path('src', 'drivers', 'ADC', 'OC_util_ADC.h'))

# DAC: values go to the virtual hardware instead of the SPI bus
s = read(path('OC_DAC.cpp'))
s = s.replace('#include "util/util_SPIFIFO.h"', '#include <Arduino.h>')
s = re.sub(r'\n\s*if \(F_BUS == 60000000 \|\| F_BUS == 48000000\)\s*\n\s*SPIFIFO\.begin\([^;]*;', '\n', s)
s = re.sub(r'(void DAC::init_Vbias\(\) \{).*?\n\}', r'\1\n}', s, flags=re.S)
s = re.sub(r'(void DAC::set_Vbias\(uint32_t data\) \{).*?\n\}', r'\1\n  (void) data;\n}', s, flags=re.S)
s = s[:s.index('void set8565_CHA')] + read(os.path.join(DRV, 'dac_tail.cpp'))
write(path('OC_DAC.cpp'), s)

# portable versions of the inline assembly in util_math.h
s = read(path('util', 'util_math.h'))
s = s.replace('__asm("usat %0, %1, %2" : "=r" (result) : "I" (16), "r" (value));\n  return result;',
              'result = value > 65535u ? 65535u : value;\n  return result;', 1)
s = s.replace('__asm("usat %0, %1, %2" : "=r" (result) : "I" (16), "r" (value));\n  return result;',
              'result = value < 0 ? 0 : (value > 65535 ? 65535 : value);\n  return result;', 1)
s = s.replace('register uint32_t lo, hi;\n  asm volatile("umull %0, %1, %2, %3" : "=r" (lo), "=r" (hi) : "r" (a), "r" (b));\n  return (lo >> 24) | (hi << 8);',
              'return (uint32_t) (((uint64_t) a * b) >> 24);')
s = s.replace('register uint32_t lo, hi;\n  asm volatile("umull %0, %1, %2, %3" : "=r" (lo), "=r" (hi) : "r" (a), "r" (b));\n  return (lo >> shift) | (hi << (32 - shift));',
              'return (uint32_t) (((uint64_t) a * b) >> shift);')
if 'asm' in s.replace('// asm', ''):
    raise SystemExit('util_math.h: assembly left')
write(path('util', 'util_math.h'), s)

# GCC on x86 is stricter than the Teensy toolchain about a few constructs
for root, _, files in os.walk(DST):
    for name in files:
        if name.endswith(('.h', '.cpp', '.ino')):
            f = os.path.join(root, name)
            t = read(f)
            u = re.sub(r'FOURCC = FOURCC<', 'FOURCC = ::FOURCC<', t)
            if u != t:
                write(f, u)
sub('extern/stmlib_utils_random.cpp', '#include "utils/stmlib_utils_random.h"', '#include "stmlib_utils_random.h"')
sub('src/drivers/weegfx.cpp', 'void Graphics::print(uint32_t value, size_t width)', 'void Graphics::print(uint32_t value, unsigned width)')

# keep the EEPROM layout of the Teensy (size_t is 4 bytes there)
sub('braids_quantizer.h', '  size_t num_notes;', '  uint32_t num_notes;')

# Rack saves the patch: store the current app and every app's settings, as a long press in the
# app list does on the hardware (requested by the module through ochw::hw.saveRequest)
sub('o_c_REV.ino', '  while (true) {\n', '''  while (true) {
    if (ochw::hw.saveRequest) {
      OC::save_global_settings();
      OC::save_app_data();
      ochw::hw.saveRequest = false;
    }
''')

# The Arduino IDE declares every function of the sketch before compiling it; do the same
proto = re.compile(r'^((?:void|bool|size_t|int|uint\w*_t|int\w*_t|float)\s+\w+\s*\([^;{)]*\))\s*\{', re.M)
lines = ['// Generated by tools/port.py: prototypes of the sketch functions (as the Arduino IDE adds)']
for name in sorted(n for n in os.listdir(DST) if n.endswith('.ino')):
    text = read(path(name))
    for m in proto.finditer(text):
        # only functions at file scope (not inside a namespace or class)
        before = re.sub(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', '', text[:m.start()], flags=re.S)
        if before.count('{') != before.count('}'):
            continue
        sig = re.sub(r'\s*=\s*[^,)]+', '', m.group(1))  # drop default arguments
        lines.append(sig + ';')
write(path('sketch_prototypes.h'), '\n'.join(lines) + '\n')

print('ported into', DST)
